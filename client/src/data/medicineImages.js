/**
 * Helper to get the canonical image URL for a given medicine object or brand name.
 */
export function getMedicineImageUrl(med) {
  if (!med) return null;
  if (med.imageUrl) return med.imageUrl;

  const brand = (med.brandName || med.name || '').trim();
  if (MEDICINE_IMAGES[brand]) {
    return MEDICINE_IMAGES[brand];
  }

  // Case-insensitive / prefix matching fallback
  const brandLower = brand.toLowerCase();
  for (const [key, url] of Object.entries(MEDICINE_IMAGES)) {
    if (key.toLowerCase() === brandLower || brandLower.includes(key.toLowerCase()) || key.toLowerCase().includes(brandLower)) {
      return url;
    }
  }

  return null;
}
